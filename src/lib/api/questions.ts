import * as Crypto from 'expo-crypto';

import { submit } from '@/lib/offline/outbox';
import { overlayQuestions } from '@/lib/offline/overlays';
import { readThrough } from '@/lib/offline/read-through';
import { supabase } from '@/lib/supabase';
import type { PatternSource, PrepareQuestion } from '@/lib/supabase';

// Port of the web app's src/lib/api/questions.ts. Writes go through the
// outbox (lib/offline/outbox.ts), so a question jotted down offline is kept
// on the phone and sent later; the read falls back to the last copy and lays
// unsent changes over it. Writes still throw when the server rejects them,
// which is what the callers' error handling expects.

export async function fetchQuestionsForAppointment(appointmentId: string): Promise<PrepareQuestion[]> {
  const rows = await readThrough(`questions.${appointmentId}`, async () => {
    const { data, error } = await supabase
      .from('prepare_questions')
      .select('*')
      .eq('appointment_id', appointmentId)
      .order('is_priority', { ascending: false })
      .order('sort_order', { ascending: true });

    if (error) throw error;
    return (data || []) as PrepareQuestion[];
  });
  return overlayQuestions(rows, appointmentId);
}

async function send(...args: Parameters<typeof submit>): Promise<void> {
  const result = await submit(...args);
  if (result.status === 'rejected') throw new Error(result.error);
}

/** Create a new question (appends to end of list for given priority group). */
export async function createQuestion(
  userId: string,
  appointmentId: string,
  questionText: string,
  isPriority: boolean = false,
  isAutoGenerated: boolean = false,
  sourcePatternId?: string,
  sourcePatternSource?: PatternSource
): Promise<PrepareQuestion> {
  // From the list as this phone knows it, unsent questions included, rather
  // than a server read — which offline can't happen. Every reorder rewrites
  // sort_order from 0 anyway, so an occasional tie only matters until then.
  const existing = await fetchQuestionsForAppointment(appointmentId).catch(() => [] as PrepareQuestion[]);
  const sortOrder = existing.reduce((max, q) => Math.max(max, q.sort_order), -1) + 1;

  const now = new Date().toISOString();
  const row = {
    // Made here so a resend is recognised as the same question.
    id: Crypto.randomUUID(),
    user_id: userId,
    appointment_id: appointmentId,
    question_text: questionText,
    is_priority: isPriority,
    is_auto_generated: isAutoGenerated,
    source_pattern_id: sourcePatternId ?? null,
    source_pattern_source: sourcePatternSource ?? null,
    sort_order: sortOrder,
    is_addressed: false,
    created_at: now,
    updated_at: now,
  };
  await send(userId, 'question.create', { row });
  return row as PrepareQuestion;
}

/** Applies `updates` to `question` and returns the result, which is what the
 *  server will hold once the change is sent. */
export async function updateQuestion(
  question: PrepareQuestion,
  updates: Partial<Omit<PrepareQuestion, 'id' | 'user_id' | 'created_at'>>
): Promise<PrepareQuestion> {
  await send(question.user_id, 'question.update', { id: question.id, updates });
  return { ...question, ...updates };
}

/** Sets sort_order for a list of question IDs (for reordering). */
export async function reorderQuestions(userId: string, questionIds: string[], isPriority: boolean): Promise<void> {
  await send(userId, 'question.reorder', { ids: questionIds, isPriority });
}

export async function deleteQuestion(question: PrepareQuestion): Promise<void> {
  await send(question.user_id, 'question.delete', { id: question.id });
}

export async function markQuestionAddressed(question: PrepareQuestion, isAddressed: boolean): Promise<PrepareQuestion> {
  return updateQuestion(question, { is_addressed: isAddressed });
}
